function declarationSurface(node, c) {
  if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node))
    return node.getText();
  if (ts.isFunctionDeclaration(node)) return signature(node) + ";";
  if (!ts.isClassDeclaration(node) || !node.name) return "";
  const members = node.members
    .filter(
      (member) =>
        publicMember(member) &&
        member.name &&
        !docs(member).includes("@internal"),
    )
    .map((member) => {
      if (ts.isPropertyDeclaration(member)) {
        const readonly = (member.modifiers ?? []).some(
          (modifier) => modifier.kind === ts.SyntaxKind.ReadonlyKeyword,
        );
        return `  ${readonly ? "readonly " : ""}${member.name.getText()}: ${memberType(member, c)};`;
      }
      if (ts.isGetAccessorDeclaration(member))
        return `  readonly ${member.name.getText()}: ${memberType(member, c)};`;
      if (ts.isMethodDeclaration(member)) return `  ${signature(member)};`;
      return "";
    })
    .filter(Boolean);
  return `export class ${node.name.text} {\n${members.join("\n")}\n}`;
}
